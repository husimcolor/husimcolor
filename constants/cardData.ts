// 휴심컬러 컬러+도형 심리카드 데이터 (v2 - 카드별 역할 명확화)
// 9가지 컬러 × 7가지 도형 = 63장 카드
//
// 카드 위치별 해석 역할:
//   1번 카드 (psychologyFlow)  → 무의식 / 깊은 내면 / 근원 심리 흐름
//   2번 카드 (personalityFlow) → 현재 의식 흐름 / 현실 반응 / 현재 상태
//   3번 카드 (recoveryDirection) → 회복 방향 / 앞으로 필요한 에너지 / 구체적 행동 제안

export type ShapeType = 'circle' | 'triangle' | 'inverted_triangle' | 'square' | 'diamond' | 'pentagon' | 'hexagon';
export type CardColorType = 'red' | 'orange' | 'yellow' | 'green' | 'blue' | 'navy' | 'purple' | 'white' | 'black';

export interface CardData {
  id: string;
  color: CardColorType;
  shape: ShapeType;
  colorKor: string;
  shapeKor: string;
  colorHex: string;
  shapeSymbol: string;
  energyTitle: string;
  // 1번 카드용: 무의식 / 깊은 내면 / 근원 심리
  psychologyFlow: string;
  // 2번 카드용: 현재 의식 흐름 / 현실 반응 / 현재 상태
  personalityFlow: string;
  // 감정 패턴 (공통)
  emotionPattern: string;
  // 장점
  strengths: string[];
  // 보완 컬러 - { name, meaning } 형태로 의미 포함
  complementColors: { name: string; meaning: string }[];
  // 3번 카드용: 회복 방향 + 구체적 행동 제안
  recoveryDirection: string;
  // 코칭 메시지
  coachingMessage: string;
  // 보완 루틴 - 추천 차·호흡·생활 루틴
  wellness: {
    tea: string;       // 추천 차
    breath: string;    // 추천 호흡
    routine: string[]; // 추천 생활 루틴 (2~3가지)
  };
}

