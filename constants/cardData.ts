// 카드 ID로 카드 데이터 조회
export function getCardById(id: string): CardData | undefined {
  return CARD_DATA.find(card => card.id === id);
}

// 컬러와 도형으로 카드 데이터 조회
export function getCardByColorAndShape(color: CardColorType, shape: ShapeType): CardData | undefined {
  return CARD_DATA.find(card => card.color === color && card.shape === shape);
}

// 전체 카드 수 확인
export function getTotalCardCount(): number {
  return CARD_DATA.length;
}

